"""Work counts/query plans on host SQLite, not Android UI or power measurements."""
from contextlib import closing
import sqlite3
import unittest

from test_download_queue_sql import create, java_constant


def history(name):
    return java_constant("DownloadHistory." + name)


AUTOMATIC = history("AUTOMATIC")
DATE = history("DATE")
SIZE = history("SIZE")
PROJECTION = history("CARD_COLUMNS")
DUPLICATE = history("DUPLICATE_SQL")
PENDING = "SELECT 1 FROM downloads WHERE " + AUTOMATIC + " LIMIT 1"
QUEUE = ("SELECT id,status,attempt_token,wifi_only,error_message,substr(url,1,5) FROM downloads "
         "WHERE status IN (?,?,?,?,?,?) ORDER BY " + DATE + " ASC,id")
STATES = ("PENDING", "CONNECTING", "RUNNING", "WAITING_FOR_WIFI", "WAITING_FOR_BATTERY", "WAITING_FOR_SCHEDULE")
CHANGED = (f"SELECT {PROJECTION} FROM downloads INDEXED BY sqlite_autoindex_downloads_1 "
           "WHERE id IS NOT NULL AND status='COMPLETED' AND id IN (?,?,?,?)")
RESERVATIONS = "SELECT id,dest_path,temp_path FROM downloads WHERE (" + java_constant("UNKEYED_PATHS") + ") AND id<>?"


def steps(db, sql, args):
    n = 0

    def visit():
        nonlocal n
        n += 1
        return 0

    db.set_progress_handler(visit, 1)
    try:
        result = db.execute(sql, args).fetchall()
    finally:
        db.set_progress_handler(None, 0)
    return result, n


def plan(db, sql, args):
    return "; ".join(row[-1] for row in db.execute("EXPLAIN QUERY PLAN " + sql, args))


def seed_completed(db, amount):
    db.executemany("INSERT INTO downloads (id,url,file_name,name_order,name_search,status,created_time,total_bytes,downloaded_bytes,"
                   "dest_path,destination_key) VALUES (?,'fixture','Sample.ZIP','sample.zip','sample.zip','COMPLETED',7,100,100,?,?)",
                   ((f"hist-{i:06d}", f"/synthetic/{i}", f"/synthetic/{i}") for i in range(amount)))


def seek_page(key, index, descending):
    """Mirror the two limited seeks generated by Query.page for an unfiltered sort."""
    direction, op = ("DESC", "<") if descending else ("ASC", ">")
    bind = "?" if key == "name_order" else "(?+0)"
    select = (f"SELECT {PROJECTION}, {key} AS seek_key FROM downloads INDEXED BY {index} "
              "WHERE id IS NOT NULL AND ")
    tied = f"{select}{key}={bind} AND id{op}? ORDER BY id {direction} LIMIT 49"
    later = f"{select}{key}{op}{bind} ORDER BY {key} {direction},id {direction} LIMIT 49"
    return f"SELECT * FROM ({tied}) UNION ALL SELECT * FROM ({later}) ORDER BY seek_key {direction}, id {direction} LIMIT 49"


class DownloadHistorySqlTest(unittest.TestCase):
    def test_idle_and_active_queue_queries_do_not_scale_with_completed_history(self):
        all_counts = []
        for history_size in (0, 1000, 50_000):
            with closing(sqlite3.connect(":memory:")) as db:
                create(db)
                seed_completed(db, history_size)
                idle, idle_count = steps(db, PENDING, ())
                self.assertEqual([], idle)
                self.assertIn("SEARCH downloads USING COVERING INDEX downloads_status_date", plan(db, PENDING, ()))
                db.executemany("INSERT INTO downloads (id,url,status,name_order,file_name,created_time,downloaded_bytes) VALUES "
                               "(?,? ,?,'sample.zip','Sample.ZIP',?,?)", [
                                   ("waiting", "fixture", "WAITING_FOR_SCHEDULE", 10, 5),
                                   ("active", "fixture", "RUNNING", 11, 6),
                                   ("blob", "blob:fixture", "PAUSED", 13, 7),
                                   ("cancelled", "fixture", "CANCELLED", 15, 8),
                               ])
                active, active_count = steps(db, PENDING, ())
                self.assertEqual([(1,)], active)
                queue, queue_count = steps(db, QUEUE, STATES)
                self.assertEqual(["waiting", "active"], [row[0] for row in queue])
                self.assertIn("SEARCH downloads USING INDEX downloads_status_date", plan(db, QUEUE, STATES))
                duplicate, duplicate_count = steps(db, DUPLICATE, ("sample.zip",))
                self.assertEqual([("active", 6)], duplicate)
                self.assertIn("SEARCH downloads USING INDEX downloads_incomplete_name", plan(db, DUPLICATE, ("sample.zip",)))
                paths, path_count = steps(db, RESERVATIONS, ("no-exception",))
                self.assertEqual([], paths)
                self.assertIn("downloads_unkeyed_paths", plan(db, RESERVATIONS, ("no-exception",)))
                all_counts.append((idle_count, active_count, queue_count, duplicate_count, path_count))
        self.assertEqual(all_counts[0], all_counts[1])
        self.assertEqual(all_counts[0], all_counts[2])

    def test_changed_rows_remain_point_reads_in_a_large_completed_filter(self):
        counts = []
        for amount in (1000, 50_000):
            with closing(sqlite3.connect(":memory:")) as db:
                create(db)
                seed_completed(db, amount)
                args = ("hist-000007", "hist-000001", "absent", "hist-000999")
                rows, cost = steps(db, CHANGED, args)
                self.assertEqual(["hist-000001", "hist-000007", "hist-000999"], sorted(row[0] for row in rows))
                self.assertIn("SEARCH downloads USING INDEX sqlite_autoindex_downloads_1", plan(db, CHANGED, args))
                counts.append(cost)
        # A seek miss may take a different VM branch at different B-tree/table positions.
        self.assertLess(max(counts), 130)
        self.assertLessEqual(max(counts) - min(counts), 3)

    def test_a_deep_equal_key_page_seeks_without_rescanning_previous_rows(self):
        with closing(sqlite3.connect(":memory:")) as db:
            create(db)
            seed_completed(db, 50_000)
            for key, index, key_arg in ((DATE, "downloads_date", "7"), (SIZE, "downloads_size", "100"),
                                        ("name_order", "downloads_name", "sample.zip")):
                for desc in (True, False):
                    with self.subTest(key=key, desc=desc):
                        sql = seek_page(key, index, desc)
                        args = (key_arg, "hist-025000", key_arg)
                        rows, cost = steps(db, sql, args)
                        expected = range(24999, 24950, -1) if desc else range(25001, 25050)
                        self.assertEqual([f"hist-{i:06d}" for i in expected], [row[0] for row in rows])
                        self.assertIn("SEARCH downloads USING INDEX " + index, plan(db, sql, args))
                        self.assertLess(cost, 4000)  # A 25,000-row tie-prefix scan would exceed this by far.

    def test_unkeyed_path_lookup_keeps_legacy_and_live_staging_rows_only(self):
        with closing(sqlite3.connect(":memory:")) as db:
            create(db)
            seed_completed(db, 1000)
            db.executescript("""
                INSERT INTO downloads (id,url,status,dest_path) VALUES ('legacy','fixture','COMPLETED','/alias/out');
                INSERT INTO downloads (id,url,status,dest_path,destination_key,temp_path) VALUES
                    ('owner','fixture','PAUSED','/real/out','/real/out','/alias/stage.part');
            """)
            result, _ = steps(db, RESERVATIONS, ("another",))
            self.assertEqual([("legacy", "/alias/out", None), ("owner", "/real/out", "/alias/stage.part")], result)
            result, _ = steps(db, RESERVATIONS, ("owner",))
            self.assertEqual([("legacy", "/alias/out", None)], result)


if __name__ == "__main__":
    unittest.main()
